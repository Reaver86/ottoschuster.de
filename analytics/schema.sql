CREATE TABLE IF NOT EXISTS analytics_events (
 id CHAR(32) CHARACTER SET ascii NOT NULL,
 site VARCHAR(32) CHARACTER SET ascii NOT NULL,
 day DATE NOT NULL,
 event VARCHAR(32) CHARACTER SET ascii NOT NULL,
 path VARCHAR(100) CHARACTER SET ascii NOT NULL,
 referrer VARCHAR(253) CHARACTER SET ascii NOT NULL,
 device VARCHAR(10) CHARACTER SET ascii NOT NULL,
 visitor CHAR(64) CHARACTER SET ascii NOT NULL,
 PRIMARY KEY(site,id), KEY period(site,day), KEY visitor_limit(site,day,visitor)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS analytics_reports (
 period CHAR(7) CHARACTER SET ascii PRIMARY KEY,
 status VARCHAR(20) NOT NULL,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
